library(data.table)
source_file <- "data/raw/soynam_20261031/met.RData"
if (!file.exists(source_file)) stop("The source file has not been downloaded.")
if (file.info(source_file)$size != 932380) stop("The source file size differs from the repository record.")
environment <- new.env()
loaded <- load(source_file, envir = environment)
print(loaded)
print(lapply(mget(loaded, envir = environment), dim))
print(head(environment$Obs, 12L))
print(lapply(environment$Obs, class))
print(summary(environment$Obs))
print(head(rownames(environment$Gen), 12L))
print(head(colnames(environment$Gen), 12L))
genotypes <- as.matrix(environment$Gen)
print(class(environment$Gen))
print(table(as.vector(genotypes), useNA = "always"))
observations <- as.data.table(environment$Obs)
print(observations[, .(rows = .N, lines = uniqueN(ID), blocks = uniqueN(Block)), by = Year])
print(observations[, .(measurements = .N), by = ID][, .(lines = .N), by = measurements][order(measurements)])
print(observations[, lapply(.SD, function(x) sum(is.na(x))), .SDcols = names(observations)])
print(observations[DTM > 180])
print(observations[, .(rows = .N, lines = uniqueN(ID)), by = .(Year, Block)])
